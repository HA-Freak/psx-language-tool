# Rasterises Cascadia Mono (SIL Open Font License, ships with Windows 11) into
# an anti-aliased bitmap font for the ELF:  pwsh tools/elf/gen_font.ps1  -> font.h
# Cell: 10 x 18 pixels, 16 alpha levels (0..15) per pixel, ASCII 32..126.
# Extra glyphs: 1 = Cross button, 2 = Circle button, 3 = up/down arrows.
param([string]$Out = "$PSScriptRoot/font.h", [string]$Font = "Cascadia Mono", [float]$Size = 15.5)
Add-Type -AssemblyName System.Drawing
$W = 10; $H = 18
$bmp = New-Object System.Drawing.Bitmap($W, $H)
$g = [System.Drawing.Graphics]::FromImage($bmp)
$g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::AntiAliasGridFit
$g.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias
$f = New-Object System.Drawing.Font($Font, $Size, [System.Drawing.FontStyle]::Bold, [System.Drawing.GraphicsUnit]::Pixel)
if ($f.Name -ne $Font) { throw "font $Font not found (got $($f.Name))" }
$fmt = [System.Drawing.StringFormat]::GenericTypographic
$white = [System.Drawing.Brushes]::White
$pen = New-Object System.Drawing.Pen([System.Drawing.Color]::White, 2.0)

function Grab {
    $o = @()
    for ($y = 0; $y -lt $H; $y++) {
        for ($x = 0; $x -lt $W; $x++) {
            $p = $bmp.GetPixel($x, $y)
            $o += [int][math]::Round(($p.R + $p.G + $p.B) / 3 / 17)
        }
    }
    return , $o
}

$glyphs = @{}
for ($c = 32; $c -le 126; $c++) {
    $g.Clear([System.Drawing.Color]::Black)
    $g.DrawString([string][char]$c, $f, $white, 0, -2, $fmt)
    $glyphs[$c] = Grab
}
# 1: cross button
$g.Clear([System.Drawing.Color]::Black)
$g.DrawLine($pen, 1, 4, 9, 12); $g.DrawLine($pen, 9, 4, 1, 12)
$glyphs[1] = Grab
# 2: circle button
$g.Clear([System.Drawing.Color]::Black)
$g.DrawEllipse($pen, 0.9, 3.9, 8.6, 8.6)
$glyphs[2] = Grab
# 3: up/down arrows
$g.Clear([System.Drawing.Color]::Black)
$g.FillPolygon($white, [System.Drawing.PointF[]]@((New-Object System.Drawing.PointF(5, 1.5)), (New-Object System.Drawing.PointF(9, 7)), (New-Object System.Drawing.PointF(1, 7))))
$g.FillPolygon($white, [System.Drawing.PointF[]]@((New-Object System.Drawing.PointF(5, 16.5)), (New-Object System.Drawing.PointF(9, 11)), (New-Object System.Drawing.PointF(1, 11))))
$glyphs[3] = Grab

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("/* generated by gen_font.ps1 from $Font (SIL OFL) - do not edit */")
[void]$sb.AppendLine("#define FONT_W $W")
[void]$sb.AppendLine("#define FONT_H $H")
[void]$sb.AppendLine("static const unsigned char font_glyph[127][$($W*$H)] = {")
for ($c = 0; $c -le 126; $c++) {
    if ($glyphs.ContainsKey($c)) {
        [void]$sb.AppendLine("  [$c] = {" + ($glyphs[$c] -join ",") + "},")
    }
}
[void]$sb.AppendLine("};")
[IO.File]::WriteAllText($Out, $sb.ToString())
"written $Out"
